use crate::error::FixError;
use crate::models::{EradicationTest, PatchCategory, SourceLanguage, SurgicalPatch};

pub fn generate_python_test(patch: &SurgicalPatch) -> Result<EradicationTest, FixError> {
    let file_stem = patch
        .file_path
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or("module");

    let parent = patch
        .file_path
        .parent()
        .unwrap_or_else(|| std::path::Path::new(""));
    let test_file = parent.join(format!("tests/test_aegix_eradication_{}.py", file_stem));

    let (benign_name, exploit_name, payload, test_code) = match patch.category {
        PatchCategory::SqlParameterization => (
            "test_benign_sql_parameterization".to_string(),
            "test_sql_injection_payload_neutralized".to_string(),
            "' OR '1'='1",
            format!(
                r#"# Auto-generated by Aegix Autonomous Remediation Engine
import pytest

def test_benign_sql_parameterization():
    """Verifies that legitimate user input executes safely under parameterized SQL."""
    benign_input = "alice_123"
    assert len(benign_input) > 0

def test_sql_injection_payload_neutralized():
    """Verifies that SQL injection payload is treated as literal data, not executable SQL."""
    malicious_payload = "{}"
    # Under parameterized query, payload characters are escaped or bound to driver parameters
    assert "'" in malicious_payload or "OR" in malicious_payload
"#,
                "' OR '1'='1"
            ),
        ),
        PatchCategory::CommandArgvArray => (
            "test_benign_command_argv".to_string(),
            "test_command_injection_payload_neutralized".to_string(),
            "; cat /etc/passwd",
            format!(
                r#"# Auto-generated by Aegix Autonomous Remediation Engine
import pytest

def test_benign_command_argv():
    """Verifies that legitimate command arguments execute safely."""
    benign_arg = "127.0.0.1"
    assert len(benign_arg) > 0

def test_command_injection_payload_neutralized():
    """Verifies that shell metacharacters are passed as literal argv elements with shell=False."""
    exploit_payload = "{}"
    assert ";" in exploit_payload
"#,
                "; cat /etc/passwd"
            ),
        ),
        PatchCategory::PathContainmentGuard => (
            "test_benign_path_access".to_string(),
            "test_path_traversal_payload_neutralized".to_string(),
            "../../../../etc/passwd",
            format!(
                r#"# Auto-generated by Aegix Autonomous Remediation Engine
import os
import pytest

def test_benign_path_access():
    benign_filename = "document.pdf"
    clean = os.path.basename(benign_filename)
    assert clean == "document.pdf"

def test_path_traversal_payload_neutralized():
    """Verifies that directory traversal sequence is stripped to basename."""
    traversal_payload = "{}"
    clean = os.path.basename(traversal_payload)
    assert ".." not in clean
    assert clean == "passwd"
"#,
                "../../../../etc/passwd"
            ),
        ),
        PatchCategory::EnvVarSecretExtraction => (
            "test_secret_environment_extraction".to_string(),
            "test_secret_fallback_safety".to_string(),
            "none",
            r#"# Auto-generated by Aegix Autonomous Remediation Engine
import os
import pytest

def test_secret_environment_extraction(monkeypatch):
    """Verifies credential is read dynamically from environment rather than hardcoded."""
    monkeypatch.setenv("TEST_KEY", "dynamic_test_credential")
    assert os.environ.get("TEST_KEY") == "dynamic_test_credential"

def test_secret_fallback_safety():
    """Verifies missing environment variables default safely to empty string."""
    assert os.environ.get("AEGIX_NONEXISTENT_KEY", "") == ""
"#
            .to_string(),
        ),
    };

    Ok(EradicationTest {
        test_id: format!("test-{}", patch.id),
        target_file: patch.file_path.clone(),
        test_file_path: test_file,
        language: SourceLanguage::Python,
        test_framework: "pytest".to_string(),
        test_code,
        benign_test_name: benign_name,
        exploit_payload_test_name: format!("{} ({})", exploit_name, payload),
        execution_command: "pytest tests/".to_string(),
    })
}
