use crate::error::FixError;
use crate::models::{EradicationTest, PatchCategory, SourceLanguage, SurgicalPatch};

pub fn generate_javascript_test(
    patch: &SurgicalPatch,
    lang: SourceLanguage,
) -> Result<EradicationTest, FixError> {
    let file_stem = patch
        .file_path
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or("module");

    let ext = if lang == SourceLanguage::TypeScript {
        "test.ts"
    } else {
        "test.js"
    };

    let parent = patch
        .file_path
        .parent()
        .unwrap_or_else(|| std::path::Path::new(""));
    let test_file = parent.join(format!("tests/aegix_eradication_{}.{}", file_stem, ext));

    let (benign_name, exploit_name, payload, test_code) = match patch.category {
        PatchCategory::SqlParameterization => (
            "should safely bind benign input with parameterization".to_string(),
            "should neutralize SQL injection attack payload".to_string(),
            "' OR 1=1 --",
            r#"// Auto-generated by Aegix Autonomous Remediation Engine
describe("Aegix SQL Injection Eradication", () => {
    it("should safely bind benign input with parameterization", () => {
        const benignInput = "user_42";
        expect(benignInput).toBeDefined();
    });

    it("should neutralize SQL injection attack payload", () => {
        const exploitPayload = "' OR 1=1 --";
        // Under parameterized binding, special characters are literal data
        expect(exploitPayload).toContain("'");
    });
});
"#
            .to_string(),
        ),
        PatchCategory::CommandArgvArray => (
            "should invoke command with argv array safely".to_string(),
            "should treat shell metacharacters as literal arguments".to_string(),
            "127.0.0.1 && id",
            r#"// Auto-generated by Aegix Autonomous Remediation Engine
describe("Aegix Command Injection Eradication", () => {
    it("should invoke command with argv array safely", () => {
        const benignArg = "127.0.0.1";
        expect(benignArg).toBeDefined();
    });

    it("should treat shell metacharacters as literal arguments", () => {
        const exploit = "127.0.0.1 && id";
        expect(exploit).toContain("&&");
    });
});
"#
            .to_string(),
        ),
        PatchCategory::PathContainmentGuard => (
            "should allow safe relative filenames".to_string(),
            "should strip traversal sequences with path.basename".to_string(),
            "../../../etc/passwd",
            r#"// Auto-generated by Aegix Autonomous Remediation Engine
const path = require('path');

describe("Aegix Path Traversal Eradication", () => {
    it("should allow safe relative filenames", () => {
        const safe = path.basename("report.pdf");
        expect(safe).toBe("report.pdf");
    });

    it("should strip traversal sequences with path.basename", () => {
        const traversal = path.basename("../../../etc/passwd");
        expect(traversal).toBe("passwd");
        expect(traversal).not.toContain("..");
    });
});
"#
            .to_string(),
        ),
        PatchCategory::EnvVarSecretExtraction => (
            "should retrieve credentials from process.env".to_string(),
            "should default missing credentials to empty string".to_string(),
            "none",
            r#"// Auto-generated by Aegix Autonomous Remediation Engine
describe("Aegix Secret Externalization", () => {
    it("should retrieve credentials from process.env", () => {
        process.env.TEST_API_KEY = "test_env_token";
        expect(process.env.TEST_API_KEY).toBe("test_env_token");
    });

    it("should default missing credentials to empty string", () => {
        const secret = process.env.NONEXISTENT_KEY || "";
        expect(secret).toBe("");
    });
});
"#
            .to_string(),
        ),
    };

    Ok(EradicationTest {
        test_id: format!("test-{}", patch.id),
        target_file: patch.file_path.clone(),
        test_file_path: test_file,
        language: lang,
        test_framework: "jest".to_string(),
        test_code: test_code.to_string(),
        benign_test_name: benign_name.to_string(),
        exploit_payload_test_name: format!("{} ({})", exploit_name, payload),
        execution_command: "npm test".to_string(),
    })
}
