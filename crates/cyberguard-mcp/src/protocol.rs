//! Canonical MCP protocol data models complying with MCP Specification v2024-11-05 and JSON-RPC 2.0.

#![deny(unsafe_code)]

use crate::error::JsonRpcError;
use serde::{Deserialize, Serialize};
use std::collections::HashMap;

pub const MCP_PROTOCOL_VERSION: &str = "2024-11-05";

/// Polymorphic JSON-RPC 2.0 Request ID (supports integer or string identifiers).
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(untagged)]
pub enum RequestId {
    Int(i64),
    String(String),
}

/// Standard JSON-RPC 2.0 Request Envelope.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct JsonRpcRequest {
    pub jsonrpc: String,
    #[serde(default)]
    pub id: Option<RequestId>,
    pub method: String,
    #[serde(default)]
    pub params: Option<serde_json::Value>,
}

impl JsonRpcRequest {
    /// Returns true if this message is a notification (no ID present).
    pub fn is_notification(&self) -> bool {
        self.id.is_none()
    }
}

/// Standard JSON-RPC 2.0 Response Envelope.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct JsonRpcResponse {
    pub jsonrpc: String,
    pub id: Option<RequestId>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub result: Option<serde_json::Value>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub error: Option<JsonRpcError>,
}

impl JsonRpcResponse {
    pub fn success(id: Option<RequestId>, result: serde_json::Value) -> Self {
        Self {
            jsonrpc: "2.0".to_string(),
            id,
            result: Some(result),
            error: None,
        }
    }

    pub fn error(id: Option<RequestId>, error: JsonRpcError) -> Self {
        Self {
            jsonrpc: "2.0".to_string(),
            id,
            result: None,
            error: Some(error),
        }
    }
}

