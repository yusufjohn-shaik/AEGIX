//! MITRE ATT&CK Navigator Layer (v4.5 / v5.0) JSON generator.

#![deny(unsafe_code)]

use crate::models::{
    AttackNavigatorLayer, MitreMatrixDomain, NavigatorFilters, NavigatorGradient, NavigatorLayout,
    NavigatorMetadataEntry, NavigatorTechniqueEntry, NavigatorVersions, ThreatFinding,
};
use crate::scorer::ThreatScorer;
use std::collections::{BTreeMap, HashMap};

/// Generator for official MITRE ATT&CK Navigator Layer JSON.
pub struct NavigatorGenerator {
    scorer: ThreatScorer,
}

impl Default for NavigatorGenerator {
    fn default() -> Self {
        Self::new(ThreatScorer::default())
    }
}

impl NavigatorGenerator {
    pub fn new(scorer: ThreatScorer) -> Self {
        Self { scorer }
    }

    /// Generates an AttackNavigatorLayer from findings and target domain.
    pub fn generate_layer(
        &self,
        name: &str,
        domain: MitreMatrixDomain,
        findings: &[ThreatFinding],
    ) -> AttackNavigatorLayer {
        // Group findings by (technique_id, tactic_slug)
        let mut grouped: BTreeMap<(String, String), Vec<&ThreatFinding>> = BTreeMap::new();

        for finding in findings {
            for tech_id in &finding.techniques {
                // If finding has associated tactics, map to each tactic slug; otherwise default to primary
                if finding.tactics.is_empty() {
                    grouped
                        .entry((tech_id.clone(), "enterprise-attack".to_string()))
                        .or_default()
                        .push(finding);
                } else {
                    for tactic in &finding.tactics {
                        grouped
                            .entry((tech_id.clone(), tactic.slug().to_string()))
                            .or_default()
                            .push(finding);
                    }
                }
            }
        }

        let mut techniques = Vec::new();

        for ((tech_id, tactic_slug), tech_findings) in grouped {
            let score = self.scorer.score_technique(&tech_findings);
            let findings_count = tech_findings.len();

            let mut cwe_set = HashMap::new();
            for f in &tech_findings {
                for cwe in &f.cwe_ids {
                    cwe_set.insert(*cwe, ());
                }
            }
            let mut cwe_list: Vec<String> = cwe_set.keys().map(|c| format!("CWE-{}", c)).collect();
            cwe_list.sort();

            let cwe_summary = if cwe_list.is_empty() {
                String::new()
            } else {
                format!(" ({})", cwe_list.join(", "))
            };

            let comment = format!(
                "Aegix detected {} finding(s) mapped to {}{}",
                findings_count, tech_id, cwe_summary
            );

            let primary_stride = tech_findings
                .first()
                .and_then(|f| f.stride_categories.first())
                .map(|s| s.title())
                .unwrap_or("Unknown");

            let metadata = vec![
                NavigatorMetadataEntry {
                    name: "findingsCount".to_string(),
                    value: findings_count.to_string(),
                },
                NavigatorMetadataEntry {
                    name: "primaryStride".to_string(),
                    value: primary_stride.to_string(),
                },
            ];

            techniques.push(NavigatorTechniqueEntry {
                technique_id: tech_id,
                tactic: tactic_slug,
                score: Some(score),
                color: None, // Omitted so Navigator dynamically interpolates from gradient
                comment: Some(comment),
                enabled: true,
                metadata,
            });
        }

        AttackNavigatorLayer {
            name: name.to_string(),
            versions: NavigatorVersions::default(),
            domain: domain.as_str().to_string(),
            description: format!(
                "Automated Threat Model and ATT&CK Matrix generated by Aegix for domain '{}'",
                domain.as_str()
            ),
            filters: Some(NavigatorFilters::default()),
            gradient: NavigatorGradient::default(),
            layout: Some(NavigatorLayout::default()),
            techniques,
        }
    }
}
